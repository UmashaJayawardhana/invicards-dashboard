-- ------------------------------------------------------------------------------
-- 4. Automatic Trigger on auth.users for customer_profiles
-- ------------------------------------------------------------------------------
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
declare
  v_role text;
  v_username text;
  v_full_name text;
begin
  v_role := coalesce(new.raw_user_meta_data->>'role', 'customer');
  if v_role not in ('admin', 'customer') then
    v_role := 'customer';
  end if;

  v_username := coalesce(new.raw_user_meta_data->>'username', split_part(new.email, '@', 1));
  v_full_name := coalesce(new.raw_user_meta_data->>'full_name', '');

  insert into public.customer_profiles (user_id, username, full_name, role)
  values (new.id, v_username, v_full_name, v_role)
  on conflict (user_id) do update set
    username = coalesce(excluded.username, public.customer_profiles.username),
    full_name = coalesce(excluded.full_name, public.customer_profiles.full_name),
    role = excluded.role;

  return new;
exception
  when unique_violation then
    insert into public.customer_profiles (user_id, username, full_name, role)
    values (new.id, null, v_full_name, v_role)
    on conflict (user_id) do update set
      role = excluded.role;
    return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

-- ------------------------------------------------------------------------------
-- 5. Sync existing users into customer_profiles
-- ------------------------------------------------------------------------------
insert into public.customer_profiles (user_id, username, full_name, role)
select 
  id, 
  coalesce(raw_user_meta_data->>'username', split_part(email, '@', 1)),
  coalesce(raw_user_meta_data->>'full_name', ''),
  coalesce(raw_user_meta_data->>'role', 'customer')
from auth.users
on conflict (user_id) do nothing;
