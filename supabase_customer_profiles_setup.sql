-- ------------------------------------------------------------------------------
-- 1. Table: public.customer_profiles
-- ------------------------------------------------------------------------------
create table if not exists public.customer_profiles (
  user_id uuid not null,
  username character varying(100) null,
  full_name character varying(150) null,
  created_at timestamp with time zone null default now(),
  role text not null default 'customer'::text,
  constraint customer_profiles_pkey primary key (user_id),
  constraint customer_profiles_username_key unique (username),
  constraint customer_profiles_user_id_fkey foreign key (user_id) references auth.users (id) on delete cascade,
  constraint customer_profiles_role_check check (role in ('admin', 'customer'))
);

alter table public.customer_profiles enable row level security;

drop policy if exists "Allow select on customer_profiles" on public.customer_profiles;
create policy "Allow select on customer_profiles"
  on public.customer_profiles for select
  using (true);

drop policy if exists "Allow insert on customer_profiles" on public.customer_profiles;
create policy "Allow insert on customer_profiles"
  on public.customer_profiles for insert
  with check (true);

drop policy if exists "Allow update on customer_profiles" on public.customer_profiles;
create policy "Allow update on customer_profiles"
  on public.customer_profiles for update
  using (true) with check (true);

